"""Valida o esquema, os privilégios e as consultas do SADA em um PostgreSQL 16 real.

Uso:  python scripts/validar_pg.py [--json resultado.json]

Requisitos: cliente `psql` no PATH e um usuário PostgreSQL com perfil de superusuário,
informado pelas variáveis de ambiente padrão (PGHOST, PGPORT, PGUSER, PGPASSWORD).
O script cria o banco descartável `sada_validacao` e o papel `sada_leitura`, executa
as verificações e remove ambos ao final. Não usa Django nem psycopg.
"""
import argparse
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(RAIZ))
from academico import simulacao                  # noqa: E402
from painel import indicadores as ind            # noqa: E402

BANCO = "sada_validacao"
TABELAS = ["inativo", "curso", "gradecurricular", "disciplina", "gradedisciplina",
           "professor", "periodoletivo", "aluno", "turma", "diario"]
STUB = ("CREATE TABLE auth_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "username VARCHAR(150) UNIQUE NOT NULL);\n")   # no uso normal, o Django cria auth_user
ALUNO = ("INSERT INTO aluno (codigoaluno,matricula,anoingresso,semestreingresso,codigoturno,"
         "codigocurso,nomealuno,codigograde) VALUES (900001,'{m}',{a},{s},3,1,'Teste',1)")
NEGATIVOS = [  # (descrição, SQL, trecho esperado na mensagem de erro)
    ("Nota fora da faixa (nota1 = 11)", "UPDATE diario SET nota1=11 WHERE codigodiario=1", "diario_nota1_check"),
    ("Nota negativa (nota2 = -1)", "UPDATE diario SET nota2=-1 WHERE codigodiario=1", "diario_nota2_check"),
    ("Faltas negativas", "UPDATE diario SET faltas=-3 WHERE codigodiario=1", "diario_faltas_check"),
    ("Resultado inválido", "UPDATE diario SET resultado='XYZ' WHERE codigodiario=1", "diario_resultado_check"),
    ("Diário duplicado", "INSERT INTO diario (codigodiario,codigoaluno,codigoturma) SELECT 900001,"
     "codigoaluno,codigoturma FROM diario LIMIT 1", "diario_codigoaluno_codigoturma_key"),
    ("Turma inexistente", "INSERT INTO diario (codigodiario,codigoaluno,codigoturma) VALUES (900002,1,999999)",
     "diario_codigoturma_fkey"),
    ("Período com data final anterior à inicial",
     "INSERT INTO periodoletivo VALUES (900,2030,1,'2030-06-01','2030-02-01')", "periodoletivo_check"),
    ("Matrícula repetida", "INSERT INTO aluno (codigoaluno,matricula,anoingresso,semestreingresso,codigoturno,"
     "codigocurso,nomealuno,codigograde) SELECT 900001,matricula,anoingresso,semestreingresso,codigoturno,"
     "codigocurso,'Teste',1 FROM aluno LIMIT 1", "aluno_matricula_key"),
    ("Matrícula com 9 dígitos", ALUNO.format(m="210123002", a=2021, s=2), "ck_matricula_formato"),
    ("Matrícula com caracteres não numéricos", ALUNO.format(m="21A1230020", a=2021, s=2), "ck_matricula_formato"),
    ("Matrícula incoerente com o ano de ingresso", ALUNO.format(m="2201230020", a=2021, s=2), "ck_matricula_coerencia"),
    ("Matrícula incoerente com o semestre", ALUNO.format(m="2101130020", a=2021, s=2), "ck_matricula_coerencia"),
    ("Papel de leitura tenta ler o CPF", "SET ROLE sada_leitura; SELECT cpf FROM aluno LIMIT 1",
     "permission denied for table aluno"),
    ("Papel de leitura tenta alterar o diário", "SET ROLE sada_leitura; UPDATE diario SET nota1=0 WHERE codigodiario=1",
     "permission denied for table diario"),
]


def psql(sql, banco=BANCO, check=True):
    """Executa SQL com o psql; devolve o processo concluído (stdout/stderr em texto)."""
    r = subprocess.run(["psql", "-X", "-q", "-t", "-A", "-v", "ON_ERROR_STOP=1", "-d", banco],
                       input=sql, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise RuntimeError(sql[:200] + "\n" + r.stderr)
    return r


def inteiro(sql):
    return int(psql(sql).stdout.strip())


def linhas(sql):
    return [l.split("|") for l in psql(sql + ";").stdout.strip().splitlines()]


def limpar():
    psql(f"DROP DATABASE IF EXISTS {BANCO}; DROP ROLE IF EXISTS sada_leitura;", "postgres")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", help="grava o resultado em um arquivo JSON")
    args = ap.parse_args()

    limpar()
    psql(f"CREATE DATABASE {BANCO} ENCODING 'UTF8' TEMPLATE template0 "
         f"LC_COLLATE 'C.UTF-8' LC_CTYPE 'C.UTF-8'", "postgres")
    versao = psql("SELECT version();").stdout.strip()
    print(versao)
    psql(STUB + (RAIZ / "sql/schema.sql").read_text(encoding="utf8"))
    psql((RAIZ / "sql/papeis.sql").read_text(encoding="utf8"))
    publico = "table_schema='public' AND table_name <> 'auth_user'"
    por_tipo = lambda c: inteiro(
        "SELECT count(*) FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid "
        f"WHERE t.relnamespace='public'::regnamespace AND t.relname<>'auth_user' AND c.contype='{c}'")
    est = {"tabelas": inteiro(f"SELECT count(*) FROM information_schema.tables WHERE {publico}"),
           "check": por_tipo("c"), "fk": por_tipo("f"), "unique": por_tipo("u"),
           "indices": inteiro("SELECT count(*) FROM pg_indexes WHERE schemaname='public' "
                              "AND indexname LIKE 'ix\\_%'")}
    print("estrutura:", est)

    # carga da base simulada por \copy (CSV gerado em diretório temporário)
    base = simulacao.gerar_base()
    t0 = time.perf_counter()
    with tempfile.TemporaryDirectory() as tmp:
        for nome in TABELAS:
            df = base[nome]
            arq = Path(tmp) / f"{nome}.csv"
            df.to_csv(arq, index=False, header=False, na_rep="")
            psql(f"\\copy {nome} ({', '.join(df.columns)}) FROM '{arq}' WITH (FORMAT csv, NULL '')")
    carga = round(time.perf_counter() - t0, 2)
    cont = {n: inteiro(f"SELECT count(*) FROM {n}") for n in TABELAS}
    print("carga:", carga, "s", cont)
    psql("ANALYZE;")

    # operações que devem ser rejeitadas
    neg = []
    for desc, sql, esperado in NEGATIVOS:
        r = psql(sql + ";", check=False)
        ok = r.returncode != 0 and esperado in r.stderr
        tipo = ("PRIVILÉGIO" if "permission" in esperado else "UNIQUE" if esperado.endswith("_key")
                else "FOREIGN KEY" if esperado.endswith("_fkey") else "CHECK")
        neg.append({"caso": desc, "tipo": tipo, "restricao": esperado, "rejeitado": ok})
        print(("OK    " if ok else "FALHA ") + f"{desc}  [{esperado}]")
    leitura = psql("SET ROLE sada_leitura; SELECT count(nomealuno) FROM aluno;", check=False).returncode == 0
    print("papel de leitura lê as colunas permitidas:", leitura)

    # consultas analíticas: tempo (mediana de 7 execuções) e conferência com o pandas
    texto = (RAIZ / "sql/indicadores.sql").read_text(encoding="utf8")
    qs = ["\n".join(l for l in q.split("\n") if not l.strip().startswith("--")).strip()
          for q in texto.split(";") if "SELECT" in q]
    tempos = []
    for i, q in enumerate(qs, 1):
        ms = sorted(json.loads(psql(f"EXPLAIN (ANALYZE, FORMAT JSON) {q};").stdout)[0]["Execution Time"]
                    for _ in range(7))
        tempos.append({"q": f"Q{i}", "linhas": len(linhas(q)), "mediana_ms": round(ms[3], 2),
                       "max_ms": round(ms[-1], 2)})
        print(f"Q{i}: mediana {ms[3]:.2f} ms, máximo {ms[-1]:.2f} ms")

    df = ind.preparar(base)
    q1 = {r[1]: r for r in linhas(qs[0])}
    d = ind.aprovacao_por_disciplina(df)
    ok1 = len(q1) == len(d) and all(
        int(q1[e.nomedisciplina][2]) == e.registros
        and abs(float(q1[e.nomedisciplina][3]) - e.taxa_aprovacao) < 0.051
        and abs(float(q1[e.nomedisciplina][4]) - e.media) < 0.0051 for e in d.itertuples())
    ev = ind.evolucao_por_periodo(df)
    r2 = linhas(qs[1])
    ok2 = len(r2) == len(ev) and all(
        r[0] == e.periodo and int(r[1]) == e.registros and abs(float(r[2]) - e.taxa_aprovacao) < 0.051
        and abs(float(r[3]) - e.media) < 0.0051 and abs(float(r[4]) - e.frequencia) < 0.051
        for r, e in zip(r2, ev.itertuples()))
    cur = df[(df.periodo == df.periodo.max()) & df.risco.notna()]
    ok3 = {r[0] for r in linhas(qs[2])} == set(cur.matricula)
    cr = ind.cr_por_aluno(df)
    q4 = {r[0]: float(r[1]) for r in linhas(qs[3])}
    ok4 = len(q4) == len(cr) and all(abs(q4[e.matricula] - e.cr) < 0.0051 for e in cr.itertuples())
    co = ind.situacao_por_coorte(base)
    r5 = linhas(qs[4])
    ok5 = len(r5) == len(co) and all(
        r[0] == e["coorte"] and int(r[1]) == e["ingressantes"] and int(r[2]) == e["Concluído"]
        and int(r[3]) == e["Evadido"] for r, e in zip(r5, co.to_dict("records")))
    cruzada = {"Q1": ok1, "Q2": ok2, "Q3": ok3, "Q4": ok4, "Q5": ok5}
    print("SQL x pandas:", cruzada)

    if args.json:
        Path(args.json).write_text(json.dumps(
            {"versao": versao, **est, "carga_s": carga, "contagens": cont, "negativos": neg,
             "tempos": tempos, "cruzada": cruzada, "leitura_ok": leitura},
            ensure_ascii=False, indent=1), encoding="utf8")
    limpar()
    aprovado = all(n["rejeitado"] for n in neg) and leitura and all(cruzada.values())
    print("\nRESULTADO:", "tudo conforme." if aprovado else "HÁ FALHAS (veja acima).")
    return 0 if aprovado else 1


if __name__ == "__main__":
    sys.exit(main())
